"""Brownian spectral density and exact T=0 cumulant utilities."""

from __future__ import annotations

import math

import numpy as np
from scipy.special import expi

from config import (
    CENTER_FREQUENCY_EV,
    CUMULANT_FFT_MULTIPLIER,
    CUMULANT_SUBSTEPS,
    EV_PER_AU,
)


def spectral_density_eV(
    frequency_eV: np.ndarray,
    lambda_eV: float,
    gamma_eV: float,
    center_eV: float = CENTER_FREQUENCY_EV,
) -> np.ndarray:
    r"""Return the underdamped-Brownian ``J(omega)`` in eV.

    The convention is

    ``J(w)=2 lambda Gamma omega_s^2 w /
    [(w^2-omega_s^2)^2+Gamma^2 w^2]``,

    for which ``integral_0^inf J(w)/(pi*w) dw=lambda``.
    """
    frequency_eV = np.asarray(frequency_eV, dtype=float)
    numerator = (
        2.0
        * lambda_eV
        * gamma_eV
        * center_eV**2
        * frequency_eV
    )
    denominator = (
        (frequency_eV**2 - center_eV**2) ** 2
        + gamma_eV**2 * frequency_eV**2
    )
    return numerator / denominator


def spectral_density_over_frequency_au(
    frequency: np.ndarray,
    lam: float,
    gamma: float,
    center: float,
) -> np.ndarray:
    """Return ``J(w)/w`` in atomic units, including its finite origin."""
    frequency = np.asarray(frequency, dtype=float)
    return (
        2.0
        * lam
        * gamma
        * center**2
        / (
            (frequency**2 - center**2) ** 2
            + gamma**2 * frequency**2
        )
    )


def _drude_kernel_and_derivative(
    u: np.ndarray,
) -> tuple[np.ndarray, np.ndarray]:
    r"""Evaluate the T=0 Drude kernel ``F(u)`` and ``F'(u)`` stably."""
    u = np.asarray(u, dtype=float)
    kernel = np.zeros_like(u)
    derivative = np.zeros_like(u)
    positive = u > 0.0
    value = u[positive]
    if len(value) == 0:
        return kernel, derivative

    kernel_value = np.empty_like(value)
    derivative_value = np.empty_like(value)
    small = value < 1.0e-3
    x = value[small]
    logarithm = np.euler_gamma + np.log(x)
    kernel_value[small] = (
        x**2 * (0.75 - 0.5 * logarithm)
        + x**4 * (25.0 / 288.0 - logarithm / 24.0)
    )
    derivative_value[small] = (
        x * (1.0 - logarithm)
        + x**3 * (11.0 / 36.0 - logarithm / 6.0)
    )

    direct = (value >= 1.0e-3) & (value <= 50.0)
    x = value[direct]
    positive_ei = np.exp(-x) * expi(x)
    negative_ei = np.exp(x) * expi(-x)
    kernel_value[direct] = (
        np.euler_gamma + np.log(x)
        - 0.5 * (positive_ei + negative_ei)
    )
    derivative_value[direct] = 0.5 * (
        positive_ei - negative_ei
    )

    large = value > 50.0
    x = value[large]
    inverse_squared = 1.0 / x**2
    half_sum = inverse_squared.copy()
    power = inverse_squared.copy()
    factorial = 1.0
    for order in range(1, 7):
        factorial *= (2 * order) * (2 * order + 1)
        power *= inverse_squared
        half_sum += factorial * power
    kernel_value[large] = (
        np.euler_gamma + np.log(x) - half_sum
    )
    derivative_value[large] = 1.0 / x
    for order in range(7):
        derivative_value[large] += (
            math.factorial(2 * order + 2) / x ** (2 * order + 3)
        )

    kernel[positive] = kernel_value
    derivative[positive] = derivative_value
    return kernel, derivative


def squared_lorentzian_lineshape(
    time: np.ndarray,
    h_zero: float,
    center: float,
) -> np.ndarray:
    r"""Exact cumulant generated by ``h0*a^4/(w^2+a^2)^2``.

    This auxiliary density matches both the origin and the leading
    high-frequency coefficient of the Brownian ``J(w)/w``.  It is obtained
    by differentiating the analytic Drude cumulant with respect to ``a``.
    """
    u = center * np.asarray(time, dtype=float)
    kernel, derivative = _drude_kernel_and_derivative(u)
    real = h_zero / np.pi * (
        kernel - 0.5 * u * derivative
    )
    exponential_kernel = -np.expm1(-u) - u
    exponential_derivative = np.exp(-u) - 1.0
    imag = 0.5 * h_zero * (
        exponential_kernel
        - 0.5 * u * exponential_derivative
    )
    return real + 1.0j * imag


def exact_brownian_lineshape(
    time: np.ndarray,
    lambda_mev: float,
    gamma_eV: float,
    *,
    fft_multiplier: int = CUMULANT_FFT_MULTIPLIER,
    substeps: int = CUMULANT_SUBSTEPS,
) -> np.ndarray:
    r"""Return the exact independent-boson ``T=0`` lineshape.

    ``g(t)=int J(w)[1-cos(wt)+i(sin(wt)-wt)]/(pi*w^2) dw``.

    A squared-Lorentzian reference is evaluated analytically.  The residual
    is transformed on a uniform frequency grid; it is ``O(w^2)`` at the
    origin and ``O(w^-6)`` at infinity.  This removes the infrared aliasing
    that a direct finite FFT would have for an Ohmic bath.
    """
    time = np.asarray(time, dtype=float)
    if (
        time.ndim != 1
        or len(time) < 2
        or not np.isclose(time[0], 0.0)
    ):
        raise ValueError("time must be a one-dimensional grid starting at 0")
    target_step = float(time[1] - time[0])
    if not np.allclose(
        np.diff(time), target_step, rtol=1.0e-10, atol=1.0e-10
    ):
        raise ValueError("time grid must be uniform")
    if fft_multiplier < 2 or substeps < 1:
        raise ValueError("insufficient cumulant transform padding")

    lam = lambda_mev * 1.0e-3 / EV_PER_AU
    gamma = gamma_eV / EV_PER_AU
    center = CENTER_FREQUENCY_EV / EV_PER_AU
    internal_step = target_step / substeps
    n_fft = fft_multiplier * len(time) * substeps
    delta_frequency = 2.0 * np.pi / (n_fft * internal_step)
    frequency = delta_frequency * np.arange(n_fft, dtype=float)

    h_brownian = spectral_density_over_frequency_au(
        frequency, lam, gamma, center
    )
    h_zero = 2.0 * lam * gamma / center**2
    h_reference = (
        h_zero
        * center**4
        / (frequency**2 + center**2) ** 2
    )
    residual = h_brownian - h_reference
    del h_brownian, h_reference, frequency

    # The upper-end trapezoid correction is below machine-relevant scale
    # after the O(w^-4) terms cancel.  Retain the lower half weight, which is
    # analytically zero but also suppresses roundoff in the cancellation.
    upper_bound = (
        0.5 * delta_frequency * abs(residual[-1]) / np.pi
    )
    if upper_bound > 1.0e-12:
        raise RuntimeError(
            "Cumulant frequency range is too short for its tail"
        )
    transform = np.fft.fft(residual)
    transform -= 0.5 * residual[0]
    transform *= delta_frequency
    del residual

    reference_reorganization = h_zero * center / 4.0
    residual_reorganization = lam - reference_reorganization
    derivative = (
        -transform.imag
        + 1.0j
        * (
            transform.real
            - np.pi * residual_reorganization
        )
    ) / np.pi
    del transform

    # In-place cumulative trapezoid integration on the internal time grid.
    derivative[1:] += derivative[:-1]
    derivative[1:] *= 0.5 * internal_step
    np.cumsum(derivative[1:], out=derivative[1:])
    derivative[0] = 0.0
    residual_lineshape = derivative[::substeps][: len(time)].copy()
    del derivative

    reference_lineshape = squared_lorentzian_lineshape(
        time, h_zero, center
    )
    result = reference_lineshape + residual_lineshape
    if not np.all(np.isfinite(result)):
        raise RuntimeError("Exact Brownian cumulant contains NaN or Inf")
    return result


def reorganization_sum_rule(
    lambda_eV: float,
    gamma_eV: float,
    center_eV: float = CENTER_FREQUENCY_EV,
) -> float:
    """Analytic value of ``int J(w)/(pi*w) dw`` for this convention."""
    del gamma_eV, center_eV
    return lambda_eV
